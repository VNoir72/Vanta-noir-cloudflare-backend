import assert from 'node:assert/strict';
import {createHash,webcrypto} from 'node:crypto';
import {r4Attachments,r4Pick,r4Files,r4Serve} from '../lib/stored-tech-pack-attachments.mjs';
globalThis.crypto ??= webcrypto;
const bytes=new TextEncoder().encode('%PDF-1.7 test');
const rec={kind:'pdf',file:'VN25-01-Tech-Pack-R4.pdf',key:'tech-packs/r4-20261026/VN25-01-Tech-Pack-R4.pdf',bytes:bytes.length,sha256:createHash('sha256').update(bytes).digest('hex'),color:'Wine',pages:8};
const details=JSON.stringify({manufacturingAttachments:[rec]});
assert.equal(r4Attachments(details).length,1);
assert.equal(r4Attachments('{').length,0);
assert.equal(r4Attachments({manufacturingAttachments:[{...rec,key:'private/customer-data.pdf'}]}).length,0);
assert.equal(r4Attachments({manufacturingAttachments:[{...rec,bytes:6000000}]}).length,0);
assert.equal(r4Pick(details,'asset',null,'OTHER.pdf'),null);
assert.equal(r4Pick(details,'pdf','Wrong colour',null),null);
assert.equal(r4Pick(details,'pdf',null,null).file,rec.file);
assert.match(r4Files({id:'vn-25-01',name:'A < B',details_json:details}),/A &lt; B/);
const bucket={get:async key=>{assert.equal(key,rec.key);return {size:bytes.length,arrayBuffer:async()=>bytes.buffer};}};
let response=await r4Serve(bucket,rec);assert.equal(response.status,200);assert.equal(response.headers.get('content-type'),'application/pdf');assert.equal((await response.arrayBuffer()).byteLength,bytes.length);
response=await r4Serve(bucket,{...rec,sha256:'0'.repeat(64)});assert.equal(response.status,503);
response=await r4Serve(bucket,null);assert.equal(response.status,404);
response=await r4Serve(null,rec);assert.equal(response.status,503);
console.log('11 attachment isolation, validation, integrity and rendering checks passed');
